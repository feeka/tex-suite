import {test,expect} from '@playwright/test';
test('home, 15 templates, visual editing, snapping, undo and source preservation',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:'test-results/home.png',fullPage:true});
  await page.getByRole('button',{name:'Templates 15'}).click();
  await expect(page.locator('.template-card')).toHaveCount(15);
  await page.screenshot({path:'test-results/templates.png',fullPage:true});
  await page.getByRole('button',{name:'Use Atelier template',exact:true}).click();
  await expect(page.getByTestId('page-canvas')).toBeVisible();
  await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:'test-results/beamer.png'});
  const title=page.getByTestId('page-canvas').getByTestId('element-text').filter({hasText:'Ideas worth'});
  await title.dblclick();
  await page.getByRole('textbox',{name:'Edit text on canvas'}).fill('New research\nNew possibilities.');
  await page.keyboard.press('Escape');
  await expect(title).toHaveCount(0);
  const revised=page.getByTestId('page-canvas').getByTestId('element-text').filter({hasText:'New research'});
  const b=await revised.boundingBox();
  await page.mouse.move(b.x+100,b.y+30);await page.mouse.down();await page.mouse.move(b.x-150,b.y+30,{steps:15});
  await expect(page.getByTestId('page-canvas')).toHaveClass(/margin-glow/);
  await page.mouse.up();
  await expect(page.getByRole('spinbutton',{name:'Element x',exact:true})).toHaveValue('48');
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await page.getByRole('button',{name:'Split',exact:true}).click();
  const pane=await page.locator('.stage-scroll').boundingBox(),canvas=await page.getByTestId('page-canvas').boundingBox();
  expect(canvas.width).toBeLessThan(pane.width);
  await page.locator('.cm-content').click();await page.keyboard.press('Control+End');await page.keyboard.type('\n% Custom source survives');
  await expect(page.locator('.source-banner')).toBeVisible();
  await page.getByRole('button',{name:'Visual',exact:true}).click();
  await page.getByRole('button',{name:'Text',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Custom LaTeX is active');
  await page.getByRole('button',{name:'Return to visual source'}).click();
  await expect(page.locator('.source-banner')).toHaveCount(0);
  expect(errors).toEqual([]);
});
