test('LaTeX source wraps visually without inserting line breaks in Beamer and manuscript',async({page})=>{
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error'&&!message.text().includes('Failed to load resource'))errors.push(message.text());});
  const longLine='% '+('scientific writing stays readable '.repeat(25)).trim();
  for(const kind of ['texBeamer','texManuscript']){
    await page.goto('/');
    await page.locator('.create-card').filter({hasText:kind}).click();
    await page.getByRole('button',{name:'LaTeX',exact:true}).click();
    const editor=page.locator('.cm-content');
    await editor.click();
    await page.keyboard.press('Control+End');
    await page.keyboard.insertText('\n'+longLine);
    await expect.poll(()=>editor.locator('.cm-line').last().evaluate(el=>el.textContent)).toBe(longLine);
    await page.keyboard.type(' and typed words',{delay:5});
    await expect.poll(()=>editor.locator('.cm-line').last().evaluate(el=>el.textContent)).toBe(longLine+' and typed words');
    const metrics=await editor.evaluate(el=>{
      const line=el.querySelector('.cm-line:last-child');
      return {lineHeight:line.getBoundingClientRect().height,scrollWidth:el.parentElement.scrollWidth,clientWidth:el.parentElement.clientWidth};
    });
    expect(metrics.lineHeight).toBeGreaterThan(35);
    expect(metrics.scrollWidth).toBeLessThanOrEqual(metrics.clientWidth+2);
  }
  expect(errors).toEqual([]);
});
