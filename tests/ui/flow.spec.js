import {test,expect} from '@playwright/test';
import path from 'node:path';
test('flowing manuscript wraps, formats, searches, edits tables and persists',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await page.locator('.create-card').filter({hasText:'texManuscript'}).click();
  const editor=page.getByRole('textbox',{name:'Manuscript text'});
  await expect(editor).toBeVisible();
  await page.screenshot({path:'test-results/flow-manuscript.png'});
  const text='Bacteria and phages form a complex ecosystem. '.repeat(120);
  await editor.fill(text);
  const metrics=await editor.evaluate(el=>({height:el.clientHeight,scroll:el.scrollWidth,width:el.clientWidth}));
  expect(metrics.height).toBeGreaterThan(1000);expect(metrics.scroll).toBeLessThanOrEqual(metrics.width+1);
  await page.getByRole('button',{name:'Find & replace',exact:true}).click();
  await page.getByRole('textbox',{name:'Find text',exact:true}).fill('phages');
  await page.getByRole('textbox',{name:'Replace with',exact:true}).fill('viruses');
  await page.getByRole('button',{name:'Replace all',exact:true}).click();
  await expect(editor).not.toContainText('phages');
  await editor.click();await page.keyboard.press('Control+End');await page.keyboard.press('Enter');
  await page.getByRole('button',{name:'Bold selection',exact:true}).click();
  await page.keyboard.type('Important finding');
  await expect(editor.locator('strong')).toContainText('Important finding');
  await page.getByRole('button',{name:'Bold selection',exact:true}).click();
  await page.keyboard.press('Enter');
  await page.getByRole('button',{name:'Table',exact:true}).click();
  await expect(editor.locator('table')).toBeVisible();
  await editor.locator('th').first().click();await page.keyboard.type('Species');
  await page.getByRole('button',{name:'Column',exact:true}).first().click();
  await expect(editor.locator('tr').first().locator('th,td')).toHaveCount(4);
  await page.getByLabel('Publisher format').selectOption('ieee');
  await page.getByRole('button',{name:'LaTeX',exact:true}).click();
  await expect(page.locator('.cm-content')).toContainText('\\documentclass[journal]{IEEEtran}');
  await page.waitForTimeout(700);await page.reload();
  await page.locator('.recent-card').first().click();
  await expect(page.getByLabel('Publisher format')).toHaveValue('ieee');
  await expect(page.getByRole('textbox',{name:'Manuscript text'})).toContainText('Important finding');
  expect(errors).toEqual([]);
});
