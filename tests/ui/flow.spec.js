test('images wrap alongside text and export to Word without stretching',async({page})=>{
  await page.goto('/');await page.locator('.create-card').filter({hasText:'texManuscript'}).click();
  const editor=page.getByRole('textbox',{name:'Manuscript text'});
  await editor.click();await page.keyboard.press('Control+End');await page.keyboard.press('Enter');
  const data=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=600;c.height=240;const g=c.getContext('2d');g.fillStyle='#dfece5';g.fillRect(0,0,600,240);g.fillStyle='#328bc6';g.fillRect(50,60,500,120);return c.toDataURL('image/png').split(',')[1];});
  const chooser=page.waitForEvent('filechooser');await page.getByRole('button',{name:'Image',exact:true}).click();
  await(await chooser).setFiles({name:'diagram.png',mimeType:'image/png',buffer:Buffer.from(data,'base64')});
  const image=editor.locator('.manuscript-image');
  await image.getByLabel('Image wrapping').selectOption('left');
  await image.getByLabel('Image width').fill('40');
  await expect(image).toHaveCSS('float','left');
  await expect.poll(()=>image.evaluate(el=>el.getBoundingClientRect().width/el.parentElement.getBoundingClientRect().width)).toBeGreaterThan(.38);
  const dl=page.waitForEvent('download');await page.getByRole('button',{name:'Word',exact:true}).click();
  const file=path.resolve('test-results/image-roundtrip.docx');await(await dl).saveAs(file);
  const {default:AdmZip}=await import('adm-zip');const xml=new AdmZip(file).readAsText('word/document.xml');
  const extent=xml.match(/wp:extent cx="(\d+)" cy="(\d+)"/);expect(extent).not.toBeNull();
  expect(Number(extent[1])/Number(extent[2])).toBeCloseTo(2.5,2);
  await page.screenshot({path:'test-results/image-wrapping.png'});
});
test('figure groups arrange multiple panels and generate matching LaTeX',async({page})=>{
  await page.goto('/');await page.locator('.create-card').filter({hasText:'texManuscript'}).click();
  const images=await page.evaluate(()=>['#328bc6','#7b4ba8'].map((color,index)=>{const c=document.createElement('canvas');c.width=300;c.height=180;const g=c.getContext('2d');g.fillStyle=color;g.fillRect(0,0,300,180);g.fillStyle='white';g.font='80px sans-serif';g.fillText(String.fromCharCode(65+index),120,120);return c.toDataURL('image/png').split(',')[1];}));
  const chooser=page.waitForEvent('filechooser');await page.getByRole('button',{name:'Figure group',exact:true}).click();await(await chooser).setFiles(images.map((buffer,index)=>({name:`panel-${index+1}.png`,mimeType:'image/png',buffer:Buffer.from(buffer,'base64')})));
  const group=page.locator('.figure-group');await expect(group).toBeVisible();await expect(group.locator('.figure-panel')).toHaveCount(2);
  await group.getByLabel('Panel 1 caption').fill('First observation');await group.getByLabel('Panel 2 caption').fill('Second observation');await group.getByLabel('Shared figure caption').fill('Combined experiment');
  const panelWidth=await group.locator('.figure-panel-image').first().evaluate(el=>el.getBoundingClientRect().width);
  await group.getByLabel('Panel 1 width', {exact:true}).fill('50');
  await expect.poll(()=>group.locator('.figure-panel-image').first().evaluate(el=>el.getBoundingClientRect().width)).toBeLessThan(panelWidth*.6);
  await group.getByLabel('Figure arrangement').selectOption('column');await expect(group).toHaveClass(/column/);
  await group.getByLabel('Figure arrangement').selectOption('row');await group.getByLabel('Figure span').selectOption('full');
  await page.getByRole('button',{name:'LaTeX',exact:true}).click();
  await expect(page.locator('.cm-content')).toContainText('\\begin{figure*}[!tbp]');await expect(page.locator('.cm-content')).toContainText('width=0.500\\linewidth');await expect(page.locator('.cm-content')).toContainText('First observation');await expect(page.locator('.cm-content')).toContainText('Combined experiment');
});
