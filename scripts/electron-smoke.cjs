const { _electron: electron, expect }=require('@playwright/test');
const fs=require('node:fs/promises');
const path=require('node:path');
(async()=>{
  console.log('Desktop smoke: launching application');
  const env={...process.env,TEXSUITE_TEST_DATA:path.resolve('.cache/electron-smoke')};
  delete env.ELECTRON_RUN_AS_NODE;
  const app=await electron.launch({...(process.env.TEXSUITE_PACKAGED?{executablePath:path.resolve(process.env.TEXSUITE_PACKAGED)}:{}),args:process.env.TEXSUITE_PACKAGED?[]:['.'],env,timeout:60000});
  try {
    const page=await app.firstWindow(),errors=[];
    console.log('Desktop smoke: window opened');
    page.on('pageerror',e=>errors.push(e.message));
    await page.waitForLoadState('domcontentloaded');
    await expect(page.locator('.compiler-status')).toContainText('LaTeX is ready',{timeout:30000});
    await page.locator('.create-card').filter({hasText:'texBeamer'}).click();
    await page.getByRole('textbox',{name:'Document title',exact:true}).fill('Desktop smoke test');
    await expect(page.locator('.document-title')).toContainText('Saved locally',{timeout:10000});
    const current=(await page.evaluate(()=>window.texSuite.library())).find(p=>p.title==='Desktop smoke test');
    if(!current)throw Error('Desktop project was not saved');
    const expectedPath=path.resolve('.cache/electron-smoke/projects',`${current.id}.texsuite`);
    await page.getByRole('button',{name:'File location'}).click();
    await expect(page.getByLabel('Saved project path')).toHaveText(expectedPath);
    await app.evaluate(({shell})=>{shell.showItemInFolder=file=>{global.__texSuiteRevealedProject=file;};});
    await page.getByRole('button',{name:'Open folder and select project'}).click();
    const revealed=await app.evaluate(()=>global.__texSuiteRevealedProject);
    if(revealed!==expectedPath)throw Error(`Wrong revealed project: ${revealed}`);
    await page.getByRole('button',{name:'Close dialog'}).click();
    await page.getByRole('button',{name:'Compile PDF',exact:true}).click();
    await expect(page.getByTitle('Compiled PDF')).toBeVisible({timeout:90000});
    console.log('Desktop smoke: Beamer PDF ready');
    await page.screenshot({path:'test-results/desktop-pdf.png'});
    const saved=await page.evaluate(()=>window.texSuite.library());
    if(!saved.some(p=>p.title==='Desktop smoke test'))throw Error('Desktop save failed');
    const escaped=await page.evaluate(()=>typeof window.require);
    if(escaped!=='undefined')throw Error('Renderer has Node access');
    await page.getByRole('button',{name:'TeX Suite home',exact:true}).click();
    await page.locator('.create-card').filter({hasText:'texManuscript'}).click();
    await page.getByLabel('Publisher format').selectOption('ieee');
    await expect(page.locator('.template-download')).toContainText('Original template downloaded',{timeout:90000});
    console.log('Desktop smoke: IEEE template ready');
    const archivePath=path.resolve('.cache/electron-smoke/ieee-original.zip');
    console.log('Desktop smoke: installing Save dialog test stub');
    await app.evaluate(({dialog},dest)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:dest});},archivePath);
    console.log('Desktop smoke: saving template ZIP');
    await page.getByRole('button',{name:'Save original template ZIP',exact:true}).click();
    console.log('Desktop smoke: Save button clicked');
    await expect(page.getByRole('status').filter({hasText:'Original publisher ZIP saved'})).toBeVisible();
    const originalZip=new (require('adm-zip'))(archivePath);
    if(!originalZip.getEntry('IEEEtran/IEEEtran.cls')||!originalZip.getEntry('IEEEtran/bare_jrnl.tex'))throw Error('Original publisher sources missing.');
    await page.getByRole('textbox',{name:'Manuscript text'}).fill('Text wraps automatically in the manuscript editor. '.repeat(80));
    await page.getByRole('button',{name:'Typeset PDF',exact:true}).click();
    await page.getByRole('button',{name:'Split',exact:true}).click();
    await expect(page.getByTitle('Compiled PDF')).toBeVisible({timeout:120000});
    console.log('Desktop smoke: manuscript PDF ready');
    await page.getByRole('button',{name:'Write',exact:true}).click();
    const wordPath=path.resolve('.cache/electron-smoke/word-export.docx');
    await app.evaluate(({dialog},dest)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:dest});},wordPath);
    await page.getByRole('button',{name:'Word',exact:true}).click();
    await expect(page.getByRole('status').filter({hasText:'Word document saved'})).toBeVisible({timeout:30000});
    if((await fs.stat(wordPath)).size<1000)throw Error('Word export is empty.');
    await page.screenshot({path:'test-results/desktop-flow.png'});
    const flowSaved=await page.evaluate(()=>window.texSuite.library());
    if(!flowSaved.some(p=>p.flow?.publisherId==='ieee'))throw Error('Manuscript persistence failed');
    if(errors.length)throw Error(errors.join('\n'));
    console.log('Desktop: canvas + manuscript compilation, IPC save, Word export and sandbox isolation passed.');
  } finally {await app.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
