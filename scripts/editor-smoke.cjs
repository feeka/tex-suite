const {_electron:electron,expect}=require('@playwright/test');
const path=require('node:path');
const fs=require('node:fs/promises');
const {execFileSync}=require('node:child_process');
(async()=>{
  const env={...process.env,TEXSUITE_TEST_DATA:path.resolve('.cache/editor-smoke')};
  delete env.ELECTRON_RUN_AS_NODE;
  const app=await electron.launch({...(process.env.TEXSUITE_PACKAGED?{executablePath:path.resolve(process.env.TEXSUITE_PACKAGED)}:{}),args:process.env.TEXSUITE_PACKAGED?[]:['.'],env,timeout:60000});
  try{
    const page=await app.firstWindow();
    await page.waitForLoadState('domcontentloaded');
    await expect(page.locator('.compiler-status')).toContainText('LaTeX is ready',{timeout:30000});
    await page.locator('.create-card').filter({hasText:'texBeamer'}).click();
    const projectTitle=`Beamer source proof ${Date.now()}`;
    await page.getByRole('textbox',{name:'Document title',exact:true}).fill(projectTitle);
    await page.getByRole('button',{name:'Bullets',exact:true}).click();
    await page.getByRole('textbox',{name:'Edit text on canvas'}).fill('Research question\nMain result');
    await page.keyboard.press('Escape');
    await expect(page.getByTestId('page-canvas').locator('ul li')).toHaveText(['Research question','Main result']);
    await page.getByRole('button',{name:'LaTeX',exact:true}).click();
    await expect(page.locator('.cm-content')).toBeVisible();
    const selectionStyle=await page.locator('.cm-content').evaluate(el=>({background:getComputedStyle(el,'::selection').backgroundColor,color:getComputedStyle(el,'::selection').color}));
    if(selectionStyle.background!=='rgb(40, 87, 71)'||selectionStyle.color!=='rgb(255, 255, 255)')throw Error(`Unreadable packaged source selection: ${JSON.stringify(selectionStyle)}`);
    const scroller=page.locator('.code-pane .cm-scroller');
    const scrollSize=await scroller.evaluate(el=>({viewport:el.clientHeight,document:el.scrollHeight}));
    if(scrollSize.document<=scrollSize.viewport)throw Error(`Beamer source has no scrollable editor: ${JSON.stringify(scrollSize)}`);
    const editorBox=await scroller.boundingBox();
    await page.mouse.move(editorBox.x+editorBox.width/2,editorBox.y+editorBox.height/2);
    await page.mouse.wheel(0,1200);
    await expect.poll(()=>scroller.evaluate(el=>el.scrollTop)).toBeGreaterThan(0);
    await page.locator('.cm-content').click();
    await page.keyboard.press('Control+End');
    await page.keyboard.type('\n% Edited in source mode');
    await expect(page.locator('.cm-content')).toContainText('% Edited in source mode');
    await page.keyboard.insertText('\n% '+('a readable scientific source line '.repeat(20)).trim());
    const wrap=await page.locator('.cm-content').evaluate(el=>({height:el.querySelector('.cm-line:last-child').getBoundingClientRect().height,scroll:el.parentElement.scrollWidth,width:el.parentElement.clientWidth}));
    if(wrap.height<=35||wrap.scroll>wrap.width+2)throw Error(`LaTeX word wrap failed: ${JSON.stringify(wrap)}`);
    await page.getByRole('button',{name:'Compile PDF',exact:true}).click();
    await expect(page.getByTitle('Compiled PDF')).toBeVisible({timeout:90000});
    await expect(page.locator('.code-pane')).toBeVisible();
    await expect(page.locator('.pdf-stale')).toHaveCount(0);
    await page.locator('.cm-content').click();
    await page.keyboard.press('Control+End');
    await page.keyboard.type('\n% Another edit');
    await expect(page.locator('.pdf-stale')).toBeVisible();
    await page.getByRole('button',{name:'Compile PDF',exact:true}).click();
    await expect(page.locator('.pdf-stale')).toHaveCount(0,{timeout:90000});
    await page.waitForTimeout(1200);
    await page.screenshot({path:'test-results/editor-smoke.png'});
    const editedSource='\\documentclass{beamer}\n\\begin{document}\n\\begin{frame}{Editable source}\nA real source edit works.\n\\begin{itemize}\n\\item Beamer list\n\\end{itemize}\n\\end{frame}\n\\end{document}\n';
    await page.locator('.cm-content').click();
    await page.keyboard.press('Control+A');
    await page.keyboard.insertText(editedSource);
    await expect(page.locator('.cm-content')).toContainText('A real source edit works.');
    await page.getByRole('button',{name:'Compile PDF',exact:true}).click();
    await expect(page.locator('.pdf-stale')).toHaveCount(0,{timeout:90000});
    const pdfPath=path.resolve('.cache/editor-smoke/source-proof.pdf');
    await fs.mkdir(path.dirname(pdfPath),{recursive:true});
    await app.evaluate(({dialog},dest)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:dest});},pdfPath);
    await page.evaluate(()=>window.texSuite.exportPdf());
    const pdfText=execFileSync('pdftotext',[pdfPath,'-'],{encoding:'utf8'});
    if(!pdfText.includes('A real source edit works.')||!pdfText.includes('Beamer list'))throw Error(`Edited source did not reach PDF: ${pdfText}`);
    await page.keyboard.press('Control+S');
    await expect.poll(async()=>{const projects=await page.evaluate(()=>window.texSuite.library());return projects.find(p=>p.title===projectTitle)?.sourceOverride;}).toBe(editedSource);
    await page.getByRole('button',{name:'TeX Suite home',exact:true}).click();
    await page.locator('.recent-card').filter({hasText:projectTitle}).click();
    await expect(page.locator('.cm-content')).toContainText('A real source edit works.');
    console.log('PASS: visual Beamer editing, wrapped LaTeX, full source replacement, PDF content, save and reopen.');
  }finally{await app.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
